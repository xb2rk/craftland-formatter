/**
 * Regenerate the pinned FC lexer token vocabulary from Craftland Studio's
 * installed language extension. The formatter never loads the extension at
 * runtime; this script turns static lexer evidence into a committed artifact.
 */

import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const packageRoot = resolve(scriptDirectory, "..");
const outputPath = join(packageRoot, "src", "grammar", "token-vocabulary.generated.ts");

function fail(message) {
  console.error(`grammar: ${message}`);
  process.exitCode = 1;
}

function parseArguments(argv) {
  let check = false;
  let sourcePath;

  for (const argument of argv) {
    if (argument === "--check") {
      check = true;
    } else if (argument.startsWith("-")) {
      throw new Error(`unknown option: ${argument}`);
    } else if (sourcePath === undefined) {
      sourcePath = resolve(argument);
    } else {
      throw new Error("pass at most one server_syntax.js path");
    }
  }

  return { check, sourcePath };
}

function findExtensionSyntaxPath() {
  const homeDirectory = process.env.USERPROFILE ?? process.env.HOME;
  if (!homeDirectory) {
    throw new Error("cannot determine the user home; pass server_syntax.js explicitly");
  }

  const candidates = [];
  for (const extensionsDirectory of [
    join(homeDirectory, ".vscode", "extensions"),
    join(homeDirectory, ".vscode-insiders", "extensions"),
  ]) {
    if (!existsSync(extensionsDirectory)) continue;

    for (const extensionName of readdirSync(extensionsDirectory)) {
      if (!extensionName.startsWith("craftlandstudio.ffugclanguage-")) continue;
      const syntaxPath = join(extensionsDirectory, extensionName, "dist", "server_syntax.js");
      if (existsSync(syntaxPath)) candidates.push({ extensionName, syntaxPath });
    }
  }

  candidates.sort((left, right) =>
    left.extensionName.localeCompare(right.extensionName, undefined, { numeric: true }),
  );
  const newest = candidates.at(-1);
  if (!newest) {
    throw new Error("installed craftlandstudio.ffugclanguage extension not found");
  }

  return newest.syntaxPath;
}

function extractTokenIds(source) {
  const assignments = /FCGLexer\.([A-Z_][A-Z0-9_]*)\s*=\s*(-?\d+)\s*;/g;
  const entries = [];
  const names = new Set();
  const ids = new Map();

  for (let match; (match = assignments.exec(source)) !== null; ) {
    const name = match[1];
    const id = Number(match[2]);
    // NLSEMI is a lexer-mode marker which repeats DEFINE's numeric id.
    if (name === "NLSEMI" || names.has(name)) continue;
    if (ids.has(id)) {
      throw new Error(`duplicate token id ${id}: ${ids.get(id)} and ${name}`);
    }
    names.add(name);
    ids.set(id, name);
    entries.push({ name, id });
  }

  for (const required of ["DEFINE", "IDENTIFIER", "WS", "EOS", "OTHER"]) {
    if (!names.has(required)) throw new Error(`missing required FCGLexer token: ${required}`);
  }
  if (entries.length === 0) throw new Error("no FCGLexer token assignments found");

  return entries;
}

function readProvenance(syntaxPath, source) {
  const extensionDirectory = resolve(dirname(syntaxPath), "..");
  const packagePath = join(extensionDirectory, "package.json");
  const extensionVersion = existsSync(packagePath)
    ? JSON.parse(readFileSync(packagePath, "utf8")).version ?? "unknown"
    : "unknown";

  return {
    artifact: "dist/server_syntax.js",
    extensionVersion,
    sha256: createHash("sha256").update(source).digest("hex"),
  };
}

function emit(entries, provenance) {
  const lines = [
    "/**",
    " * Token ids extracted from Craftland Studio's compiled ANTLR FCGLexer.",
    " *",
    " * @generated by scripts/gen-token-vocabulary.mjs - DO NOT EDIT BY HAND.",
    ` * Extension ${provenance.extensionVersion}; ${provenance.artifact}; sha256 ${provenance.sha256}.`,
    " */",
    "",
    "export const GRAMMAR_PROVENANCE = {",
    `  extensionVersion: ${JSON.stringify(provenance.extensionVersion)},`,
    `  artifact: ${JSON.stringify(provenance.artifact)},`,
    `  sha256: ${JSON.stringify(provenance.sha256)},`,
    `  tokenCount: ${entries.length},`,
    "} as const;",
    "",
    "/** Numeric FC token ids, mirroring FCGLexer (ANTLR). */",
    "export const TokenId = {",
  ];

  for (const { name, id } of entries) {
    lines.push(`  ${name}: ${id},`);
  }

  lines.push(
    "  EOF: -1,",
    "} as const;",
    "",
    "export type TokenId = (typeof TokenId)[keyof typeof TokenId];",
    "",
  );
  return lines.join("\n");
}

function main() {
  const { check, sourcePath } = parseArguments(process.argv.slice(2));
  const syntaxPath = sourcePath ?? findExtensionSyntaxPath();
  const source = readFileSync(syntaxPath, "utf8");
  const expected = emit(extractTokenIds(source), readProvenance(syntaxPath, source));

  if (check) {
    const actual = existsSync(outputPath) ? readFileSync(outputPath, "utf8") : "";
    if (actual !== expected) {
      fail(`generated token vocabulary is stale; run: node scripts/gen-token-vocabulary.mjs ${JSON.stringify(syntaxPath)}`);
      return;
    }
    console.log("grammar: generated token vocabulary is current");
    return;
  }

  writeFileSync(outputPath, expected, "utf8");
  console.log(`grammar: wrote ${outputPath}`);
}

try {
  main();
} catch (error) {
  fail(error instanceof Error ? error.message : String(error));
}
