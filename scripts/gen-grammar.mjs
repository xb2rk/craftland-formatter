/**
 * Regenerate the FC lexer token table from the installed Craftland extension.
 *
 * The package never reads the extension at runtime. This script turns its
 * lexer evidence into a versioned, committed TypeScript artifact instead.
 * `--check` is intentionally read-only so CI can detect grammar drift.
 */

import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const packageRoot = resolve(scriptDir, "..");
const outputPath = join(packageRoot, "src", "lex", "grammar.generated.ts");

/**
 * Report a grammar error and set the process exit code.
 *
 * @param message - error message.
 */
function fail(message) {
  console.error(`grammar: ${message}`);
  process.exitCode = 1;
}

/**
 * Parse CLI args (`--check` and optional `server_syntax.js` path).
 *
 * @param argv - args (without node/script).
 * @returns parsed options.
 */
function parseArgs(argv) {
  let check = false;
  let sourcePath;
  for (const arg of argv) {
    if (arg === "--check") {
      check = true;
    } else if (arg.startsWith("-")) {
      throw new Error(`unknown option: ${arg}`);
    } else if (sourcePath === undefined) {
      sourcePath = resolve(arg);
    } else {
      throw new Error("pass at most one server_syntax.js path");
    }
  }
  return { check, sourcePath };
}

/**
 * Locate `server_syntax.js` from the installed Craftland extension.
 *
 * @returns absolute path to `server_syntax.js`.
 */
function findExtensionSyntaxPath() {
  const home = process.env.USERPROFILE ?? process.env.HOME;
  if (!home) {
    throw new Error("cannot determine user home; pass server_syntax.js explicitly");
  }

  const candidates = [];
  for (const root of [join(home, ".vscode", "extensions"), join(home, ".vscode-insiders", "extensions")]) {
    if (!existsSync(root)) continue;
    for (const name of readdirSync(root)) {
      if (!name.startsWith("craftlandstudio.ffugclanguage-")) continue;
      const path = join(root, name, "dist", "server_syntax.js");
      if (existsSync(path)) candidates.push({ name, path });
    }
  }
  candidates.sort((a, b) => a.name.localeCompare(b.name, undefined, { numeric: true }));
  const newest = candidates.at(-1);
  if (!newest) {
    throw new Error("installed craftlandstudio.ffugclanguage extension not found");
  }
  return newest.path;
}

/**
 * Extract FCGLexer token assignments from `server_syntax.js`.
 *
 * @param source - file content.
 * @returns ordered entries `{ name, id }`.
 */
function extractTokenIds(source) {
  const assignments = /FCGLexer\.([A-Z_][A-Z0-9_]*)\s*=\s*(-?\d+)\s*;/g;
  const entries = [];
  const names = new Set();
  const ids = new Map();
  for (let match; (match = assignments.exec(source)) !== null; ) {
    const name = match[1];
    const id = Number(match[2]);
    // NLSEMI is a lexer mode marker that repeats DEFINE's id, not a token.
    if (name === "NLSEMI" || names.has(name)) {
      continue;
    }
    if (ids.has(id)) {
      throw new Error(`duplicate token id ${id}: ${ids.get(id)} and ${name}`);
    }
    names.add(name);
    ids.set(id, name);
    entries.push({ name, id });
  }
  for (const required of ["DEFINE", "IDENTIFIER", "EOS", "OTHER"]) {
    if (!names.has(required)) {
      throw new Error(`missing required FCGLexer token: ${required}`);
    }
  }
  if (entries.length === 0) {
    throw new Error("no FCGLexer token assignments found");
  }
  return entries;
}

/**
 * Build provenance for the generated artifact.
 *
 * @param syntaxPath - path to `server_syntax.js`.
 * @param source - file content.
 * @returns provenance.
 */
function readProvenance(syntaxPath, source) {
  const extensionDir = resolve(dirname(syntaxPath), "..");
  const packagePath = join(extensionDir, "package.json");
  const extensionVersion = existsSync(packagePath)
    ? JSON.parse(readFileSync(packagePath, "utf8")).version ?? "unknown"
    : "unknown";
  return {
    extensionVersion,
    artifact: "dist/server_syntax.js",
    sha256: createHash("sha256").update(source).digest("hex"),
  };
}

/**
 * Render the generated TypeScript artifact.
 *
 * @param entries - token entries.
 * @param provenance - provenance.
 * @returns file content.
 */
function emit(entries, provenance) {
  const lines = [
    "/**",
    " * Token ids extracted from Craftland Studio's compiled ANTLR FCGLexer.",
    " *",
    " * @generated by scripts/gen-grammar.mjs - DO NOT EDIT BY HAND.",
    ` * Extension ${provenance.extensionVersion}; ${provenance.artifact}; sha256 ${provenance.sha256}.`,
    " */",
    "",
    "export const GRAMMAR_PROVENANCE = {",
    `  extensionVersion: ${JSON.stringify(provenance.extensionVersion)},`,
    `  artifact: ${JSON.stringify(provenance.artifact)},`,
    `  sha256: ${JSON.stringify(provenance.sha256)},`,
    `  tokenCount: ${entries.length},`,
    "} as const;",
    "",
    "/** Numeric FC token ids, mirroring FCGLexer (ANTLR). */",
    "export const TokenId = {",
  ];
  for (const { name, id } of entries) {
    lines.push(`  ${name}: ${id},`);
  }
  lines.push("  EOF: -1,", "} as const;", "", "export type TokenId = (typeof TokenId)[keyof typeof TokenId];", "");
  return lines.join("\n");
}

/** CLI entry: generate or check the token table. */
function main() {
  const { check, sourcePath } = parseArgs(process.argv.slice(2));
  const syntaxPath = sourcePath ?? findExtensionSyntaxPath();
  const source = readFileSync(syntaxPath, "utf8");
  const expected = emit(extractTokenIds(source), readProvenance(syntaxPath, source));
  if (check) {
    const actual = existsSync(outputPath) ? readFileSync(outputPath, "utf8") : "";
    if (actual !== expected) {
      fail(`generated token table is stale; run: node scripts/gen-grammar.mjs ${JSON.stringify(syntaxPath)}`);
      return;
    }
    console.log("grammar: generated token table is current");
    return;
  }
  writeFileSync(outputPath, expected, "utf8");
  console.log(`grammar: wrote ${outputPath}`);
}

try {
  main();
} catch (error) {
  fail(error instanceof Error ? error.message : String(error));
}
